-- MNI Gudang - Kejadian produksi per work center (append-only)
-- ============================================================
-- Disimpan di folder `draft`, bukan `migrations`, agar tidak ikut terpasang tanpa persetujuan pemilik.
-- Setiap baris = hasil satu work center untuk satu item SPK pada satu waktu. Tidak ada ubah dan hapus lewat API.

CREATE TABLE IF NOT EXISTS public.produksi_log (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  tgl       DATE NOT NULL DEFAULT CURRENT_DATE,        -- tanggal produksi (bisa diisi mundur oleh PPIC bila perlu)
  spk_id    UUID NOT NULL REFERENCES public.spk (id),
  item_idx  INTEGER NOT NULL CHECK (item_idx >= 0),    -- urutan item pada SPK
  item_desc TEXT NOT NULL,                             -- salinan deskripsi (tahan terhadap revisi urutan)
  wc        TEXT NOT NULL,                             -- nama work center (mwc.nama) tempat pekerjaan sebenarnya dilakukan
  jenis     TEXT NOT NULL DEFAULT 'hasil' CHECK (jenis IN ('hasil', 'mulai', 'batal', 'void')), -- mulai = timer jalan di mesin; hasil = selesai; batal = timer dibatalkan; void = membatalkan catatan hasil lain (ref)
  target    NUMERIC,                                   -- jumlah yang dipesan sesi Mulai (agar mesin lain tidak mengerjakan batang yang sama)
  ref       TEXT,                                      -- jenis void: id kejadian yang dibatalkan
  kelompok  TEXT,                                      -- kelompok produk (Cable Tray, Cable Ladder, Cable Duct, Cover, Aksesoris), dibaca dari judul section SPK
  tipe      TEXT,                                      -- type (STU, STC, SLU, SLW, SLHD)
  material  TEXT,                                      -- material SPK (SPCC, SUS304, dan lain-lain)
  finishing TEXT,                                      -- ELG, HDG, PDC, atau Non finishing
  mesin     TEXT,                                      -- nama mesin di dalam work center (mis. Punching 20 Ton)
  operator  TEXT,                                      -- nama operator di mesin (bukan akun login)
  mulai     TIMESTAMPTZ,                               -- waktu mulai (hasil: dari timer atau diisi manual)
  selesai   TIMESTAMPTZ,
  menit     NUMERIC CHECK (menit IS NULL OR menit >= 0),   -- durasi pengerjaan
  berat     NUMERIC,                                   -- kg per pcs saat dicatat (dari SPK atau kalkulator berat)
  tonase    NUMERIC,                                   -- qty x berat (kg)
  spk_no    TEXT,                                      -- salinan nomor SPK, customer, tebal agar laporan tahan revisi
  customer  TEXT,
  tebal     TEXT,
  qty       NUMERIC NOT NULL DEFAULT 0 CHECK (qty >= 0),    -- jumlah SELESAI (baik) yang ditambahkan (bukan kumulatif)
  reject    NUMERIC NOT NULL DEFAULT 0 CHECK (reject >= 0), -- jumlah reject di langkah ini; tidak lanjut, dibuat ulang
  oleh      TEXT,                                      -- email pencatat
  ket       TEXT,
  CONSTRAINT produksi_log_ada_isi CHECK (jenis <> 'hasil' OR qty > 0 OR reject > 0),
  data      JSONB NOT NULL DEFAULT '{}'::jsonb          -- bidang tambahan aplikasi (created_by dan sejenisnya)
);
CREATE INDEX IF NOT EXISTS produksi_log_spk ON public.produksi_log (spk_id, item_idx);
CREATE INDEX IF NOT EXISTS produksi_log_wc_tgl ON public.produksi_log (wc, tgl);

ALTER TABLE public.produksi_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.produksi_log FROM PUBLIC, anon;
GRANT SELECT, INSERT ON public.produksi_log TO authenticated;

-- Baca: siapa pun yang boleh melihat SPK. Tulis: yang boleh mengubah SPK (peran produksi dan PPIC memiliki hak ubah SPK).
CREATE POLICY "produksi_log_read" ON public.produksi_log FOR SELECT TO authenticated USING (public.can_view('spk'));
CREATE POLICY "produksi_log_ins"  ON public.produksi_log FOR INSERT TO authenticated WITH CHECK (public.can_mod('spk') AND oleh = (SELECT auth.email()));
-- Tanpa kebijakan UPDATE dan DELETE: baris tidak dapat diubah atau dihapus oleh pengguna.

-- Riwayat perubahan database (migration 13) mencatat penambahan baris ini
DROP TRIGGER IF EXISTS trg_audit ON public.produksi_log;
CREATE TRIGGER trg_audit AFTER INSERT OR UPDATE OR DELETE ON public.produksi_log
  FOR EACH ROW EXECUTE FUNCTION public.audit_row();

-- Sinkron antar pengguna: ikutkan produksi_log dalam penanda perubahan (table_stamps)
CREATE OR REPLACE FUNCTION public.table_stamps()
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path = public, pg_temp AS $$
DECLARE
  t TEXT;
  v TEXT;
  res JSONB := '{}'::jsonb;
BEGIN
  FOREACH t IN ARRAY ARRAY['rm','fg','mutasi','spk','vendor','kirim','bongkar','master','mvendor','mcustomer',
                           'msupplier','marmada','rmhist','pr','opname','muser','log','mwc','produksi_log'] LOOP
    EXECUTE format(
      'SELECT count(*)::text || ''|'' || COALESCE(max(COALESCE(to_jsonb(x) ->> ''updated_at'', to_jsonb(x) ->> ''created_at'', to_jsonb(x) ->> ''at'')), '''') FROM public.%I x', t)
      INTO v;
    res := res || jsonb_build_object(t, v);
  END LOOP;
  RETURN res;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.table_stamps() FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.table_stamps() TO authenticated;
